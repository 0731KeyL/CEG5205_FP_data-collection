"""Export a GestureMLP checkpoint as a standalone Arduino C++ header."""
import argparse
import json
from pathlib import Path

import torch

HERE = Path(__file__).resolve().parent
DEFAULT = HERE / "runs" / "gesture_mlp_6class_20261105_202949_880032.pt"

PREAMBLE = """// Generated by export_arduino.py. Include in the sketch that calls predict().
#pragma once
#ifdef __AVR__
#include <avr/pgmspace.h>
#define GMLP_FLASH PROGMEM
#define GMLP_READ(p) pgm_read_float(p)
#else
#define GMLP_FLASH
#define GMLP_READ(p) (*(p))
#endif
namespace gesture_mlp {
"""

FORWARD = """
// Input: 84 unstandardized features in training order. Output: 8 logits.
inline int predict(const float features[84], float logits[8]) {
    float hidden[16];
    for (int j = 0; j < 16; ++j) hidden[j] = GMLP_READ(b1 + j);
    for (int i = 0; i < 84; ++i) {
        float z = (features[i] - GMLP_READ(mean + i)) / GMLP_READ(stddev + i);
        for (int j = 0; j < 16; ++j) hidden[j] += GMLP_READ(w1 + j*84 + i) * z;
    }
    for (int j = 0; j < 16; ++j) if (hidden[j] < 0) hidden[j] = 0;
    int best = 0;
    for (int k = 0; k < 8; ++k) {
        float sum = GMLP_READ(b2 + k);
        for (int j = 0; j < 16; ++j) sum += GMLP_READ(w2 + k*16 + j) * hidden[j];
        logits[k] = sum;
        if (sum > logits[best]) best = k;
    }
    return best;
}
} // namespace gesture_mlp
#undef GMLP_FLASH
#undef GMLP_READ
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint", type=Path, nargs="?", default=None)
    parser.add_argument("--output", type=Path, help="Destination .h file")
    args = parser.parse_args()
    if args.checkpoint is None:
        candidates = list((HERE / "runs").glob("*.pt"))
        if not candidates:
            parser.error("No checkpoints found. Train first or supply a checkpoint path.")
        args.checkpoint = max(candidates, key=lambda path: path.stat().st_mtime_ns)
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
    state = checkpoint["model_state_dict"]
    labels = checkpoint["class_names"]
    num_classes = len(labels)
    if num_classes < 2 or len(set(labels)) != num_classes:
        raise ValueError("Expected distinct class names.")
    output_layer = "network.3" if "network.3.weight" in state else "network.2"
    fields = [
        ("mean", "feature_mean", (84,)), ("stddev", "feature_std", (84,)),
        ("w1", "network.0.weight", (16, 84)), ("b1", "network.0.bias", (16,)),
        ("w2", f"{output_layer}.weight", (num_classes, 16)), ("b2", f"{output_layer}.bias", (num_classes,)),
    ]
    if set(state) != {key for _, key, _ in fields}:
        raise ValueError("Unexpected model state for the 84-16-K GestureMLP.")
    parts = [PREAMBLE]
    for name, key, shape in fields:
        t = state[key]
        if tuple(t.shape) != shape or t.dtype != torch.float32 or not t.isfinite().all():
            raise ValueError(f"Invalid parameter: {key}")
        if name == "stddev" and not (t > 0).all():
            raise ValueError("Standard deviations must be positive.")
        literals = [f"{v:.9e}f" for v in t.flatten().tolist()]
        rows = [", ".join(literals[i:i+6]) for i in range(0, len(literals), 6)]
        parts.append(f"static const float {name}[] GMLP_FLASH = {{\n" +
                     ",\n".join(rows) + "\n};\n")
    parts.append("inline const char* class_name(int id) {\n    switch (id) {")
    for i, label in enumerate(labels):
        parts.append(f"    case {i}: return {json.dumps(label)};")
    parts.append("    default: return \"unknown\";\n    }\n}")
    parts.append(FORWARD.replace("8 logits", f"{num_classes} logits").replace("logits[8]", f"logits[{num_classes}]").replace("k < 8", f"k < {num_classes}"))
    output = args.output or HERE / "arduino_export" / args.checkpoint.stem / "gesture_mlp.h"
    if output.suffix.lower() != ".h":
        parser.error("--output must be a .h file")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(parts), encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
